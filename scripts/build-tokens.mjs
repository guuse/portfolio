#!/usr/bin/env node
/**
 * Design tokens: tokens/**.json (DTCG) → Style Dictionary → two build outputs.
 *
 *   src/styles/tokens.css   custom properties on :root, inside `@layer tokens`
 *   src/styles/tokens.ts    the same tokens as a typed map, for the styleguide and for JS
 *
 * Layers: tokens/primitive (raw ramps, never used directly) → tokens/scale (type, space, radii,
 * motion) and tokens/theme/nacht.json (semantic colours). A second theme is a second file in
 * tokens/theme with the same names pointing at other primitives.
 *
 * Both files are generated (gitignored); `npm run dev`, `build` and `typecheck` run this first.
 * Naming: the path joined in kebab case, with a trailing `base` dropped from colours, so `ink.base` is
 * `--ink` and `ink.muted` is `--ink-muted`. References stay references (`var(--navy-190)`),
 * so changing a primitive restyles everything built on it.
 */
import StyleDictionary from "style-dictionary";
import { fileHeader, formattedVariables } from "style-dictionary/utils";

const HEADER = ["Generated by scripts/build-tokens.mjs from tokens/. Do not edit."];

const tokenName = (token) =>
  token.path
    .filter((part, i, all) => !(token.$type === "color" && part === "base" && i === all.length - 1))
    .join("-")
    .replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

StyleDictionary.registerTransform({
  name: "name/token",
  type: "name",
  transform: tokenName,
});

StyleDictionary.registerFormat({
  name: "css/layered-variables",
  format: async ({ dictionary, file }) => {
    const header = await fileHeader({ file, commentStyle: "long" });
    const vars = formattedVariables({
      format: "css",
      dictionary,
      outputReferences: true,
      usesDtcg: true,
      formatting: { commentStyle: "long", commentPosition: "above" },
    });
    return `${header}@layer tokens {\n  :root {\n${vars.replace(/^/gm, "    ")}\n  }\n}\n`;
  },
});

StyleDictionary.registerFormat({
  name: "typescript/token-map",
  format: async ({ dictionary, file }) => {
    const header = await fileHeader({ file, commentStyle: "short" });
    const rows = dictionary.allTokens.map((t) => {
      const doc = t.$description ? `  /** ${t.$description} */\n` : "";
      return `${doc}  ${JSON.stringify(t.name)}: { value: ${JSON.stringify(String(t.$value))}, type: ${JSON.stringify(t.$type)} },`;
    });
    return [
      header,
      "/** Every design token, by its CSS custom property name (without the leading `--`). */",
      `export const tokens = {\n${rows.join("\n")}\n} as const;\n`,
      "export type TokenName = keyof typeof tokens;\n",
      "/** `var(--name)` for a token, checked at compile time. */",
      "export const cssVar = (name: TokenName): string => `var(--${name})`;\n",
      "/** Breakpoints as numbers, for matchMedia. */",
      `export const breakpoint = { stage: ${parseInt(dictionary.allTokens.find((t) => t.name === "breakpoint-stage").$value, 10)} } as const;\n`,
    ].join("\n");
  },
});

const sd = new StyleDictionary({
  source: ["tokens/**/*.json"],
  usesDtcg: true,
  log: { verbosity: "default", warnings: "error" },
  hooks: { fileHeaders: { generated: () => HEADER } },
  platforms: {
    css: {
      transforms: ["name/token"],
      buildPath: "src/styles/",
      files: [
        { destination: "tokens.css", format: "css/layered-variables", options: { fileHeader: "generated" } },
      ],
    },
    ts: {
      transforms: ["name/token"],
      buildPath: "src/styles/",
      files: [
        { destination: "tokens.ts", format: "typescript/token-map", options: { fileHeader: "generated" } },
      ],
    },
  },
});

await sd.buildAllPlatforms();
