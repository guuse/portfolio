#!/usr/bin/env node
/**
 * Design tokens: tokens/**.json (DTCG) → Style Dictionary → build outputs in src/styles/.
 *
 *   tokens.css          custom properties inside `@layer tokens`: primitives and scales on
 *                       :root, each theme's semantic colours on its own selector
 *   tokens.ts           the default theme as a typed map (plus hex for opaque colours, and
 *                       breakpoints, sizes and durations as numbers), for the styleguide and JS
 *   tokens-preview.css  a class per token, for the styleguide (the CSP forbids style="")
 *   media.css           the breakpoints as @custom-media (integrations/custom-media.ts)
 *
 * Layers: tokens/primitive (raw ramps, built on hue tokens) → tokens/scale (type, space,
 * radii, motion, breakpoints) → tokens/theme/<name>.json (semantic colours). Every theme file
 * defines the same names; the default theme is on `:root, [data-theme="<default>"]` and every
 * other one on `[data-theme="<name>"]`, after it, so `<html data-theme="…">` switches the whole
 * site and a second theme never collides with the first. Each theme is resolved on its own,
 * so the files never merge.
 *
 * Generated files are gitignored; `npm run dev`, `build`, `typecheck` and `test` run this.
 * Naming: the path joined in kebab case, with a trailing `base` dropped from colours, so
 * `ink.base` is `--ink` and `ink.muted` is `--ink-muted`. References stay references
 * (`var(--navy-190)`), so changing a primitive restyles everything built on it.
 */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import StyleDictionary from "style-dictionary";
import { formattedVariables } from "style-dictionary/utils";
import { oklchToHex } from "./oklch.mjs";

const HEADER = "Generated by scripts/build-tokens.mjs from tokens/. Do not edit.";
export const DEFAULT_THEME = "nacht";

const tokenName = (token) =>
  token.path
    .filter((part, i, all) => !(token.$type === "color" && part === "base" && i === all.length - 1))
    .join("-")
    .replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

StyleDictionary.registerTransform({ name: "name/token", type: "name", transform: tokenName });

/** `calc(266 - 4)` → `262`, so resolved values (TS, contrast tests, hex) are plain numbers. */
export const foldCalc = (value) =>
  String(value).replace(/calc\((-?[\d.]+)\s*([+-])\s*(-?[\d.]+)\)/g, (_, a, op, b) =>
    String(Math.round((op === "+" ? +a + +b : +a - +b) * 1000) / 1000),
  );

const cssBlock = (selector, dictionary, tokens) => {
  const vars = formattedVariables({
    format: "css",
    dictionary: { ...dictionary, allTokens: tokens },
    outputReferences: true,
    usesDtcg: true,
    formatting: { commentStyle: "long", commentPosition: "above" },
  });
  return `  ${selector} {\n${vars.replace(/^/gm, "    ")}\n  }\n`;
};

/** The breakpoints as custom media: `--md` is from that width up, `--below-md` under it. */
function customMedia(allTokens) {
  const out = [];
  for (const t of allTokens.filter((t) => t.path[0] === "breakpoint")) {
    const name = t.path.slice(1).join("-"),
      v = t.$value,
      axis = t.$extensions?.["dev.ekkelenkamp.axis"] ?? "width";
    if (axis === "width") {
      out.push([name, `(width >= ${v})`], [`below-${name}`, `(width < ${v})`]);
    } else {
      out.push([name, `(height <= ${v})`], [`not-${name}`, `(height > ${v})`]);
      out.push([`landscape-${name}`, `(orientation: landscape) and (height <= ${v})`]);
    }
  }
  return out;
}

const PREVIEW = {
  color: (v) => `background: ${v};`,
  dimension: (v, name) =>
    name.startsWith("text-")
      ? `font-size: ${v};`
      : name.startsWith("radius-")
        ? `border-radius: ${v};`
        : `inline-size: ${v};`,
  fontFamily: (v) => `font-family: ${v};`,
  duration: (v) => `--preview-duration: ${v};`,
  cubicBezier: (v) => `--preview-ease: ${v};`,
};

function typescript(allTokens, themes, media) {
  const rows = allTokens.map((t) => {
    const value = foldCalc(t.$value);
    const hex = t.$type === "color" ? oklchToHex(value) : null;
    const doc = t.$description ? `  /** ${t.$description} */\n` : "";
    const extra = hex ? `, hex: ${JSON.stringify(hex)}` : "";
    return `${doc}  ${JSON.stringify(t.name)}: { value: ${JSON.stringify(value)}, type: ${JSON.stringify(t.$type)}${extra} },`;
  });
  const numbers = (filter, unit) =>
    allTokens
      .filter((t) => filter(t) && new RegExp(`^-?[\\d.]+${unit}$`).test(String(t.$value)))
      .map(
        (t) => `  ${JSON.stringify(t.name.replace(/^(breakpoint|duration)-/, ""))}: ${parseFloat(t.$value)},`,
      )
      .join("\n");
  return [
    `// ${HEADER}`,
    "",
    `/** Every design token of the default theme (${DEFAULT_THEME}), by its CSS custom property name (without the leading \`--\`). */`,
    `export const tokens = {\n${rows.join("\n")}\n} as const;\n`,
    "export type TokenName = keyof typeof tokens;\n",
    "/** `var(--name)` for a token, checked at compile time. */",
    "export const cssVar = (name: TokenName): string => `var(--${name})`;\n",
    "/** The themes, by their `data-theme` value; the first is the default (on `:root`). */",
    `export const themes = ${JSON.stringify(themes)} as const;\n`,
    "/** Breakpoints in px, for matchMedia (CSS uses the custom media in media.css). */",
    `export const breakpoint = {\n${numbers((t) => t.path[0] === "breakpoint", "px")}\n} as const;\n`,
    "/** The same queries as the custom media in media.css, for matchMedia. */",
    `export const media = {\n${media.map(([n, q]) => `  ${JSON.stringify(n)}: ${JSON.stringify(q)},`).join("\n")}\n} as const;\n`,
    "/** Sizes that are plain pixels (the header height, say), as numbers. */",
    `export const px = {\n${numbers((t) => t.$type === "dimension" && t.path[0] !== "breakpoint", "px")}\n} as const;\n`,
    "/** Durations in milliseconds, for timers that must match a CSS animation. */",
    `export const ms = {\n${numbers((t) => t.$type === "duration", "ms")}\n} as const;\n`,
  ].join("\n");
}

/** The resolved tokens of one theme: primitives, scales and that theme's file, nothing else. */
async function resolveTheme(tokensDir, themeFile) {
  const sd = new StyleDictionary({
    source: [join(tokensDir, "primitive/**/*.json"), join(tokensDir, "scale/**/*.json"), themeFile],
    usesDtcg: true,
    log: { verbosity: "default", warnings: "error" },
    platforms: { css: { transforms: ["name/token"] } },
  });
  const dictionary = await sd.getPlatformTokens("css");
  // which tokens came from the theme file (the rest are shared primitives and scales)
  dictionary.isTheme = (token) => resolve(token.filePath) === resolve(themeFile);
  return dictionary;
}

/**
 * Builds every output. `themeFiles` defaults to tokens/theme/*.json; tests pass their own,
 * and an `outDir` to write to. Resolves to the files written, by name.
 *
 * @param {{ tokensDir?: string; outDir?: string; themeFiles?: string[] }} [options]
 * @returns {Promise<Record<string, string>>}
 */
export async function buildTokens({ tokensDir = "tokens", outDir = "src/styles", themeFiles } = {}) {
  const themeDir = join(tokensDir, "theme");
  themeFiles ??= (await readdir(themeDir)).filter((f) => f.endsWith(".json")).map((f) => join(themeDir, f));
  const byName = new Map(themeFiles.map((f) => [basename(f, ".json"), f]));
  if (!byName.has(DEFAULT_THEME)) throw new Error(`tokens: no ${DEFAULT_THEME}.json among the themes`);
  const names = [DEFAULT_THEME, ...[...byName.keys()].filter((n) => n !== DEFAULT_THEME).sort()];

  const resolved = new Map();
  for (const name of names) resolved.set(name, await resolveTheme(tokensDir, byName.get(name)));

  const base = resolved.get(DEFAULT_THEME);
  // breakpoints aren't custom properties: media queries can't read those (see media.css)
  const shared = base.allTokens.filter((t) => !base.isTheme(t) && t.path[0] !== "breakpoint");
  const semantic = (name) => resolved.get(name).allTokens.filter((t) => resolved.get(name).isTheme(t));
  const expected = semantic(DEFAULT_THEME)
    .map((t) => t.name)
    .sort()
    .join(" ");
  for (const name of names) {
    const got = semantic(name)
      .map((t) => t.name)
      .sort();
    if (got.join(" ") !== expected) {
      const want = new Set(expected.split(" ")),
        have = new Set(got);
      const missing = [...want].filter((n) => !have.has(n)),
        extra = [...have].filter((n) => !want.has(n));
      throw new Error(
        `tokens: theme "${name}" must define exactly the ${DEFAULT_THEME} names` +
          (missing.length ? `; missing ${missing.join(", ")}` : "") +
          (extra.length ? `; unknown ${extra.join(", ")}` : ""),
      );
    }
  }

  const blocks = [cssBlock(":root", base, shared)];
  for (const name of names) {
    const selector = name === DEFAULT_THEME ? `:root,\n  [data-theme="${name}"]` : `[data-theme="${name}"]`;
    blocks.push(cssBlock(selector, resolved.get(name), semantic(name)));
  }
  const css = `/**\n * ${HEADER}\n */\n\n@layer tokens {\n${blocks.join("\n")}}\n`;

  const preview = base.allTokens
    .filter((t) => PREVIEW[t.$type] && t.path[0] !== "breakpoint")
    .map((t) => `  .tk-${t.name} { ${PREVIEW[t.$type](`var(--${t.name})`, t.name)} }`);
  const previewCss = `/**\n * ${HEADER}\n */\n\n@layer utilities {\n${preview.join("\n")}\n}\n`;

  const media = customMedia(base.allTokens);
  const mediaCss = `/**\n * ${HEADER}\n * Breakpoints as custom media; integrations/custom-media.ts substitutes them at build time.\n */\n\n${media.map(([n, q]) => `@custom-media --${n} ${q};`).join("\n")}\n`;

  await mkdir(outDir, { recursive: true });
  const files = {
    "tokens.css": css,
    "tokens-preview.css": previewCss,
    "media.css": mediaCss,
    "tokens.ts": typescript(base.allTokens, names, media),
  };
  for (const [file, content] of Object.entries(files)) await writeFile(join(outDir, file), content);
  return files;
}

if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? "")).href) await buildTokens();
